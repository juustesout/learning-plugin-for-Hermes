#!/usr/bin/env python3
"""Generate STATUS.md from live collect-only + plugin_status. Never writes the store."""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

STATUS_PATH = ROOT / "STATUS.md"


def collect_test_count() -> int:
    env = os.environ.copy()
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    proc = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "--collect-only",
            "-q",
            "-o",
            "addopts=",
            "tests",
        ],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        env=env,
        check=False,
    )
    for line in reversed((proc.stdout or "").splitlines()):
        text = line.strip()
        if "test collected" in text or "tests collected" in text:
            return int(text.split()[0])
    raise RuntimeError(
        "pytest --collect-only did not report a collected count:\n"
        f"stdout:\n{proc.stdout}\nstderr:\n{proc.stderr}"
    )


def _plugin_version() -> str:
    path = ROOT / "plugin.yaml"
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("version:"):
            return line.split(":", 1)[1].strip()
    return "unknown"


def _hook_label(value) -> str:
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return "unknown"


def render_status(
    *,
    collected: int,
    plugin: dict,
    generated_at: str,
    version: str,
) -> str:
    hooks = plugin.get("hooks") or {}
    feats = plugin.get("features") or {}
    log = plugin.get("opslog") or {}
    gate = plugin.get("gate") or {}
    gate_state = "open" if gate.get("open") else "closed"
    return (
        "# STATUS\n"
        "\n"
        "Generated by `python3 scripts/status.py`. Do not edit by hand.\n"
        "\n"
        f"generated_at: {generated_at}\n"
        f"plugin_version: {version}\n"
        "\n"
        "## Tests\n"
        "\n"
        f"- collected: {collected}\n"
        "\n"
        "## Hooks\n"
        "\n"
        f"- pre_tool_call: {_hook_label(hooks.get('pre_tool_call'))}\n"
        f"- post_tool_call: {_hook_label(hooks.get('post_tool_call'))}\n"
        f"- pre_llm_call: {_hook_label(hooks.get('pre_llm_call'))}\n"
        f"- llm_execution_middleware: {_hook_label(hooks.get('llm_execution_middleware'))}\n"
        "\n"
        "## Features\n"
        "\n"
        f"- import_source: {feats.get('import_source') or 'none'}\n"
        f"- last_error: {feats.get('last_error') or '-'}\n"
        "\n"
        "## Opslog (local default store, not live Hermes/Windows)\n"
        "\n"
        f"- lines: {log.get('lines', 0)}\n"
        f"- last: {log.get('last') or '-'}\n"
        f"- eligible_scrape: {log.get('eligible_scrape', 0)}\n"
        f"- consolidate_last: {(plugin.get('consolidate') or {}).get('last') or 'never'}\n"
        "\n"
        "## Gate\n"
        "\n"
        f"- state: {gate_state}\n"
        f"- n: {gate.get('n', 0)}\n"
        f"- min_n: {gate.get('min_n', 0)}\n"
        f"- n_distinct: {gate.get('n_distinct', 0)}\n"
        f"- reason: {gate.get('reason') or '-'}\n"
        "\n"
        "## Notes\n"
        "\n"
        "- `collected` must match `pytest --collect-only` on this worktree.\n"
        "- Live Hermes/Windows evidence store is not in this worktree.\n"
        "- Archived 18 Nov notes: `docs/archive/SESSION-RESUME.md`, `docs/archive/MONKEY.md`.\n"
        "- Those archive files are not current; do not copy their gate or test counts.\n"
    )


def collect_plugin_status() -> dict:
    import hermes_plugin
    import plugin_status

    class _Probe:
        def __init__(self):
            self.hooks = []
            self.middleware = []

        def register_hook(self, name, fn):
            self.hooks.append((name, fn))

        def register_middleware(self, kind, fn):
            self.middleware.append((kind, fn))

    hermes_plugin.register(_Probe())
    return plugin_status.collect_status()


def write_status(path: Path | None = None) -> Path:
    target = path or STATUS_PATH
    generated_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    text = render_status(
        collected=collect_test_count(),
        plugin=collect_plugin_status(),
        generated_at=generated_at,
        version=_plugin_version(),
    )
    target.write_text(text, encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate STATUS.md")
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="Print STATUS.md instead of writing the file",
    )
    parser.add_argument(
        "-o",
        "--output",
        default=str(STATUS_PATH),
        help="Output path (default: repo STATUS.md)",
    )
    args = parser.parse_args(argv)
    generated_at = datetime.now(timezone.utc).replace(microsecond=0).isoformat()
    text = render_status(
        collected=collect_test_count(),
        plugin=collect_plugin_status(),
        generated_at=generated_at,
        version=_plugin_version(),
    )
    if args.stdout:
        sys.stdout.write(text)
        return 0
    Path(args.output).write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
